import { test, expect } from "@playwright/test";
import { mkdir } from "node:fs/promises";
import { resolve } from "node:path";

const email = "login.fixture@xiangqi.test";
const password = process.env.AUTH_FIXTURE_PASSWORD;
test("cổng → đăng nhập → sảnh → tải lại → logout; bàn phím, lỗi và mobile", async ({ page, context }, info) => {
  if (!password) throw new Error("Chạy auth:fixture trước để tạo cấu hình local.");
  const screenshots = resolve(process.env.AUTH_SCREENSHOTS_DIR ?? "../../docs/design/screenshots/auth");
  await mkdir(screenshots, { recursive: true });
  await page.goto("/");
  await page.getByRole("link", { name: "Vào game", exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await expect(page.getByRole("heading", { name: "Đăng nhập", exact: true })).toBeVisible();
  await page.screenshot({ path: resolve(screenshots, `login-${info.project.name}.png`), fullPage: true });
  await page.getByRole("button", { name: "Đăng nhập", exact: true }).click();
  await expect(page.getByLabel("Email", { exact: true })).toBeFocused();
  await expect(page.getByText("Nhập địa chỉ email hợp lệ.")).toBeVisible();
  await page.getByLabel("Email", { exact: true }).fill(email);
  await page.getByLabel("Mật khẩu", { exact: true }).fill("intentionally-wrong");
  await page.getByRole("button", { name: "Hiện mật khẩu", exact: true }).click();
  await expect(page.getByLabel("Mật khẩu", { exact: true })).toHaveAttribute("type", "text");
  await page.getByRole("button", { name: "Ẩn mật khẩu", exact: true }).click();
  await expect(page.getByLabel("Mật khẩu", { exact: true })).toHaveAttribute("type", "password");
  await page.getByLabel("Mật khẩu", { exact: true }).press("Enter");
  await expect(page.locator("[data-error-toast]").getByRole("alert")).toContainText("Email hoặc mật khẩu không đúng.");
  await page.getByLabel("Mật khẩu", { exact: true }).fill("");
  await page.screenshot({ path: resolve(screenshots, `login-error-${info.project.name}.png`), fullPage: true });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  expect(overflow).toBe(false);
  await expect(page.getByRole("link", { name: "Đăng ký", exact: true })).toHaveAttribute("href", "/register");
  await page.getByLabel("Email", { exact: true }).focus();
  await page.keyboard.press("Tab");
  await expect(page.getByLabel("Mật khẩu", { exact: true })).toBeFocused();
  await page.keyboard.press("Tab");
  await expect(page.getByRole("button", { name: "Hiện mật khẩu", exact: true })).toBeFocused();
  await page.getByLabel("Mật khẩu", { exact: true }).fill(password);
  const loginResponse = page.waitForResponse((response) => response.url().endsWith("/api/auth/login") && response.status() === 200);
  await page.getByLabel("Mật khẩu", { exact: true }).press("Enter");
  const response = await loginResponse;
  expect(!!response.headers()["x-request-id"]).toBe(true);
  expect(response.headers()["cache-control"]).toBe("no-store");
  await expect(page).toHaveURL(/\/lobby$/);
  await expect(page.getByText("Kỳ thủ thử nghiệm", { exact: true })).toBeVisible();
  const cookies = await context.cookies();
  const refresh = cookies.find((cookie) => cookie.name === "xq_refresh");
  expect(!!refresh?.httpOnly && refresh.sameSite === "Lax").toBe(true);
  expect(await page.evaluate(() => !document.cookie.includes("xq_refresh"))).toBe(true);
  expect(await page.evaluate(() => localStorage.length === 0 && sessionStorage.length === 0)).toBe(true);
  await page.reload();
  await expect(page.getByText("Kỳ thủ thử nghiệm", { exact: true })).toBeVisible();
  await page.screenshot({ path: resolve(screenshots, `lobby-${info.project.name}.png`), fullPage: true });
  const second = await context.newPage();
  await second.goto("/lobby");
  await expect(second.getByText("Kỳ thủ thử nghiệm", { exact: true })).toBeVisible();
  // Two tabs refresh the same fixed token concurrently, then repeat after discarding results.
  const refreshInTab = (tab) => tab.evaluate(async () => { const r = await fetch("/api/auth/refresh", { method: "POST" }); return r.status; });
  expect(await Promise.all([refreshInTab(page), refreshInTab(second)])).toEqual([200, 200]);
  await second.route("**/api/auth/refresh", async (route) => {
    const upstream = await route.fetch();
    expect(upstream.status()).toBe(200);
    await upstream.dispose();
    await route.abort("failed"); // Backend completed, but this tab never receives its response.
  }, { times: 1 });
  expect(await second.evaluate(async () => { try { await fetch("/api/auth/refresh", { method: "POST" }); return false; } catch { return true; } })).toBe(true);
  expect(await refreshInTab(second)).toBe(200);
  const after = (await context.cookies()).find((cookie) => cookie.name === "xq_refresh");
  expect(after.value === refresh.value && after.expires === refresh.expires).toBe(true);
  await second.close();
  // Intercept only API traffic, so the rendered page remains available.
  await page.route("**/api/auth/refresh", (route) => route.abort("internetdisconnected"));
  await page.reload();
  await expect(page.getByRole("button", { name: "Thử lại", exact: true })).toBeVisible();
  await expect(page).toHaveURL(/\/lobby$/);
  await expect(page.locator("[data-error-toast]")).toHaveCount(1);
  await expect(page.locator("main [role=alert]")).toHaveCount(0);
  await page.getByRole("button", { name: "Đóng thông báo lỗi" }).focus();
  await page.keyboard.press("Enter");
  await expect(page.locator("[data-error-toast]")).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Thử lại", exact: true })).toBeVisible();
  await page.unroute("**/api/auth/refresh");
  await page.getByRole("button", { name: "Thử lại", exact: true }).click();
  await expect(page.getByText("Kỳ thủ thử nghiệm", { exact: true })).toBeVisible();
  const beforeLogout = await page.locator("main").boundingBox();
  await page.route("**/api/auth/logout", route => route.abort("internetdisconnected"), { times: 1 });
  await page.getByRole("button", { name: /^Tài khoản / }).click();
  await page.getByRole("menuitem", { name: "Đăng xuất", exact: true }).click();
  await expect(page.locator("[data-error-toast]")).toHaveCount(1);
  await expect(page.locator("main [role=alert]")).toHaveCount(0);
  const afterLogout = await page.locator("main").boundingBox();
  expect(afterLogout).toEqual(beforeLogout);
  if (!await page.getByRole("menuitem", { name: "Đăng xuất", exact: true }).isVisible()) await page.getByRole("button", { name: /^Tài khoản / }).click();
  await page.getByRole("menuitem", { name: "Đăng xuất", exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  expect((await context.cookies()).some((cookie) => cookie.name === "xq_refresh")).toBe(false);
  await page.goto("/lobby");
  await expect(page).toHaveURL(/\/login$/);
  await page.getByRole("link", { name: "Về cổng game", exact: true }).click();
  await page.getByRole("link", { name: "Chơi cùng thiết bị", exact: true }).click();
  await expect(page.locator(".board-intersection")).toHaveCount(90);
});
